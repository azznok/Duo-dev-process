# -*- coding: utf-8 -*-
# Writes docs/BENCHES.md from the header of each bench (what it proves, how to call it).
#   python bin/benches/benches.py              -> rewrites docs/BENCHES.md
#   python bin/benches/benches.py --check      -> exit 1 if docs/BENCHES.md is stale
#   python bin/benches/benches.py --grep WORD  -> the table rows containing WORD
# Why generate: a hand-kept list lies by the third bench added, and a list that lies costs more than
# no list. Header format (2 comment lines at the top of the script): 1) what the bench PROVES;
# 2) the call line.
import io
import os
import sys

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TARGET = os.path.join(R, "docs", "BENCHES.md")
# (folder, extension, prefix): a .py in bin/benches is a bench only if it is named bench_*.
FOLDERS = (("bin/benches", ".sh", ""), ("bin/benches", ".ps1", ""), ("bin/benches", ".py", "bench_"))
# Sourced helpers, not benches: they prove nothing on their own.
HELPERS = ("bench_pid.sh", "bench_pid.ps1", "common.sh")
CALLS = ("bash", "powershell", "pwsh", "python", "sh", "usage", ".\\", "./")

GUIDE = """## How to write a bench

A bench is a script in `bin/benches/` that PROVES one thing about the running project (a budget holds,
a save survives a restart, the harness still parses) and can be run by an agent or the gate.

1. **Two-line header**, the first two comment lines of the script:
   1. what the bench PROVES, in one sentence;
   2. how to call it (`bash bin/benches/bench_x.sh [...]`, `powershell -File bin\\benches\\bench_x.ps1 [...]`,
      `python bin/benches/bench_x.py [...]`).
2. **One verdict line** on stdout (`NAME ok ...` / `NAME KO ...`) and exit code 0 / 1. Never a 300-line
   output: an agent reads it, and every line is read again at each later call of its session.
3. **The detail goes to `logs/benches/<name>.log`** (shell: `$BENCH_LOGS` from `common.sh`).
4. **Declare the PID**: source `bench_pid.sh` / dot-source `bench_pid.ps1` first, so `stop-all.ps1`
   can kill a bench left running and the coder never closes a task while one still runs.
5. Then run `python bin/benches/benches.py` (the gate's `harness_lint.sh` fails while this table is stale).

`bench_example.sh` is the smallest bench: copy it.

## The benches

"""


def header(path):
    title, usage = "", ""
    with io.open(path, encoding="utf-8", errors="replace") as f:
        for i, line in enumerate(f):
            if i > 30:
                break
            s = line.strip()
            if s.startswith("#!") or not s.startswith("#"):
                if title:
                    break
                continue
            t = s.lstrip("#").strip()
            if not t or t.startswith("-*-"):
                continue
            if not title:
                title = t
            elif not usage and t.lower().startswith(CALLS):
                usage = t
    return title, usage


def table():
    rows = []
    for folder, ext, prefix in FOLDERS:
        d = os.path.join(R, *folder.split("/"))
        if not os.path.isdir(d):
            continue
        for n in sorted(os.listdir(d)):
            if n.endswith(ext) and n.startswith(prefix) and not n.startswith("_") and n not in HELPERS:
                title, usage = header(os.path.join(d, n))
                if title:
                    rows.append((folder + "/" + n, title, usage))
    return rows


def render(rows):
    s = ["# Benches - what each one PROVES",
         "> WRITTEN BY: `python bin/benches/benches.py` (generated from each bench's header). BUDGET: none.",
         "",
         "Do not edit this file: fix the header of the script, then run the command again.",
         "",
         GUIDE.rstrip("\n"),
         "",
         "| Script | What it proves | Call |", "|---|---|---|"]
    for path, title, usage in rows:
        u = ("`" + usage.replace("|", "/") + "`") if usage else ""
        s.append("| `%s` | %s | %s |" % (path, title.replace("|", "/"), u))
    s += ["", "_%d entries._" % len(rows), ""]
    return "\n".join(s)


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    rows = table()
    if "--grep" in sys.argv:
        word = sys.argv[sys.argv.index("--grep") + 1].lower()
        for c, t, u in rows:
            if word in (c + t + u).lower():
                print("%s : %s  [%s]" % (c, t, u))
        return 0
    text = render(rows)
    if "--check" in sys.argv:
        old = io.open(TARGET, encoding="utf-8").read() if os.path.exists(TARGET) else ""
        if old.replace("\r\n", "\n") != text:
            print("docs/BENCHES.md is stale: python bin/benches/benches.py")
            return 1
        print("docs/BENCHES.md is up to date")
        return 0
    io.open(TARGET, "w", encoding="utf-8", newline="\n").write(text)
    print("docs/BENCHES.md written (%d entries)" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
